#!/usr/bin/env node
// Reads Unity .png + .png.meta pairs from src/playables/dice-blackjack/assets/_source-unity/,
// extracts 9-slice borders from each .meta's `spriteBorder: {x, y, z, w}`, copies the PNG
// into its runtime location, and regenerates src/playables/dice-blackjack/buttons9slice.ts
// with the registry of borders + webpack imports.
//
// Designed to be re-runnable: drop fresh Unity exports into _source-unity/ and re-run.

const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '..');
const SOURCE_DIR = path.join(REPO_ROOT, 'src/playables/dice-blackjack/assets/_source-unity');
// Buttons live in the shared end_card module's asset folder — both EndCardScene
// AND dice-blackjack's PostGameUI pull from there.
const BUTTON_RUNTIME_DIR = path.join(REPO_ROOT, 'assets/end_card');
const BUTTON_RUNTIME_IMPORT_PREFIX = 'assets/end_card';
const COIN_RUNTIME_PATH = path.join(REPO_ROOT, 'assets/UI/Coin.png');
const REGISTRY_OUT_PATH = path.join(REPO_ROOT, 'src/playables/end_card/buttons9slice.ts');

// Mapping: source filename → { kind: 'button' | 'coin', exportName?: string, runtimeName?: string }
// Add entries here when new sliced assets get added.
const ASSET_MAP = {
  // The Layer Lab "Convex Rectangle" gray base is the shared button — tinted
  // per-consumer at runtime (CLAIM = green, DOUBLE = purple, CTA = green).
  'Button_Convex_Rectangle_01_Gray.png': { kind: 'button', exportName: 'convex', runtimeName: 'Button_Convex.png' },
  'ItemIcon_Coin_Gold.png':              { kind: 'coin' },
};

function parseSpriteBorder(metaPath) {
  // Unity .meta is YAML. We don't need a full parser; spriteBorder is a single
  // line like:    spriteBorder: {x: 20, y: 29, z: 20, w: 19}
  // x=left, y=bottom, z=right, w=top (Unity convention).
  const text = fs.readFileSync(metaPath, 'utf8');
  const match = text.match(/spriteBorder:\s*\{x:\s*([-\d.]+),\s*y:\s*([-\d.]+),\s*z:\s*([-\d.]+),\s*w:\s*([-\d.]+)\}/);
  if (!match) {
    throw new Error(`No spriteBorder found in ${path.basename(metaPath)} — is this a sprite (not a regular texture)?`);
  }
  return {
    left:   Math.round(parseFloat(match[1])),
    bottom: Math.round(parseFloat(match[2])),
    right:  Math.round(parseFloat(match[3])),
    top:    Math.round(parseFloat(match[4])),
  };
}

function main() {
  if (!fs.existsSync(SOURCE_DIR)) {
    console.error(`Source dir missing: ${SOURCE_DIR}`);
    process.exit(1);
  }
  fs.mkdirSync(BUTTON_RUNTIME_DIR, { recursive: true });

  const sourceFiles = fs.readdirSync(SOURCE_DIR).filter(f => f.endsWith('.png'));
  if (sourceFiles.length === 0) {
    console.error(`No .png files in ${SOURCE_DIR}. Drop your Unity exports there and re-run.`);
    process.exit(1);
  }

  const buttons = [];
  let coinUpdated = false;

  for (const file of sourceFiles) {
    const mapping = ASSET_MAP[file];
    if (!mapping) {
      console.warn(`  skip ${file} — no entry in ASSET_MAP (add one to scripts/extract-9slice-blackjack.js)`);
      continue;
    }
    const srcPng = path.join(SOURCE_DIR, file);

    if (mapping.kind === 'button') {
      const metaPath = srcPng + '.meta';
      if (!fs.existsSync(metaPath)) {
        console.error(`  ERROR ${file}: missing ${path.basename(metaPath)} — need the .meta for 9-slice borders`);
        process.exit(1);
      }
      const border = parseSpriteBorder(metaPath);
      const destPng = path.join(BUTTON_RUNTIME_DIR, mapping.runtimeName);
      fs.copyFileSync(srcPng, destPng);
      buttons.push({ exportName: mapping.exportName, runtimeName: mapping.runtimeName, border });
      console.log(`  button ${mapping.exportName}: border L${border.left} T${border.top} R${border.right} B${border.bottom}`);
    } else if (mapping.kind === 'coin') {
      fs.copyFileSync(srcPng, COIN_RUNTIME_PATH);
      coinUpdated = true;
      console.log(`  coin: copied → assets/UI/Coin.png`);
    }
  }

  if (buttons.length === 0 && !coinUpdated) {
    console.error('Nothing extracted. Check that source filenames match ASSET_MAP entries.');
    process.exit(1);
  }

  // Generate the TypeScript registry. Only emitted if we found at least one button
  // (the coin is consumed through a different import path).
  if (buttons.length > 0) {
    const importLines = buttons
      .map(b => `import ${b.exportName}Url from '${BUTTON_RUNTIME_IMPORT_PREFIX}/${b.runtimeName}';`)
      .join('\n');
    const entries = buttons
      .map(b => `  ${b.exportName}: {\n    url: ${b.exportName}Url,\n    border: { left: ${b.border.left}, top: ${b.border.top}, right: ${b.border.right}, bottom: ${b.border.bottom} },\n  },`)
      .join('\n');

    const content = `// AUTOGENERATED by scripts/extract-9slice-blackjack.js — do not edit by hand.
// Regenerate by running: npm run extract:dice-blackjack-9slice
${importLines}

export interface NineSliceBorders {
  left: number;
  top: number;
  right: number;
  bottom: number;
}

export interface NineSliceAsset {
  url: string;
  border: NineSliceBorders;
}

export const buttons9slice: Record<string, NineSliceAsset> = {
${entries}
};
`;
    fs.writeFileSync(REGISTRY_OUT_PATH, content);
    console.log(`\nWrote ${path.relative(REPO_ROOT, REGISTRY_OUT_PATH)} with ${buttons.length} button(s).`);
  }

  if (coinUpdated) {
    console.log('\nCoin swapped. Existing imports of assets/UI/Coin.png/.webp pick up the new texture next build.');
    console.log('(Also re-run any .webp generator if you keep both formats in sync.)');
  }
}

main();
